#include "pch.h"

cpu_fsm_base::cpu_fsm_base()
{
	pPendingParam = nullptr;
	preGlobalTotalTime = 0.0f;
	postGlobalTotalTime = 0.0f;
	totalTime = 0.0f;
	pParent = nullptr;
}

cpu_fsm_base::~cpu_fsm_base()
{
}

////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////

void cpu_fsm_base::Initialize()
{
	pReleaseItems = new std::list<_RELEASE>();
}

void cpu_fsm_base::Uninitialize()
{
	for ( auto it=pReleaseItems->begin() ; it!=pReleaseItems->end() ; ++it )
	{
		_RELEASE& obj = *it;
		obj.func(obj.pInst);
	}
	CPU_DELPTR(pReleaseItems);
}

bool cpu_fsm_base::IsRunning()
{
	if ( IsActive()==false )
		return false;
	if ( pParent )
		return pParent->IsRunning();
	return true;
}
