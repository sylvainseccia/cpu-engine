#include "pch.h"

cpu_fsm_base::cpu_fsm_base()
{
	state = -1;
	pending = -1;
	pPendingParam = nullptr;
	preGlobalTotalTime = 0.0f;
	postGlobalTotalTime = 0.0f;
	totalTime = 0.0f;
	pParent = nullptr;
}

cpu_fsm_base::~cpu_fsm_base()
{
}

////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////

void cpu_fsm_base::ToState(int to, void* pParam)
{
	pending = to;
	pPendingParam = pParam;
}

bool cpu_fsm_base::IsRunning()
{
	if ( IsActive()==false )
		return false;
	if ( pParent )
		return pParent->IsRunning();
	return true;
}
